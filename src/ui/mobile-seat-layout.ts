// ========================================
// ★モバイルUI★ 両サイドの席の割り振り（純粋関数・DOM非依存・テスト対象）
//
// 他プレイヤーを画面上端の横スクロール1行に並べていたが、
//  - 5人を超えると画面外へはみ出し、スクロールしないと見えない人が出る
//  - 全員が上端の一箇所に固まるため、対人リアクションの投擲が短く、
//    誰から誰へ飛んだのか分からない
// という問題があった。そこで場（フェルト）の左右に席を立てる。
//
// 並びの規則は PC UI と同じ空間原則:
//   自分の席＝画面下（手札エリア）。★自分の次の手番の人が「左の下」★で、
//   そこから左列を上へ → 右列を上から下へ降りて自分に戻る。
//   ＝卓を時計回りに囲む並びになり、場の環（⟳）の向きと一致する。
//
// リバースしても上がっても席は動かさない（PC UIと同じ。動かすと誰がどこに
// いるのか分からなくなる。向きは環の反転で伝える）。
//
// 手番順そのものは pc/seat-layout.ts の othersInTurnOrder を共有する
// （UI非依存なので二重に実装しない）。ここが持つのは「左右への割り振り」だけ。
// ========================================

export interface MobileSeatColumns {
  /** 左列（DOMに並べる順＝上から下） */
  left: string[];
  /** 右列（DOMに並べる順＝上から下） */
  right: string[];
}

/**
 * 手番順に並んだ他プレイヤーを左右の列に割り振る。
 *
 * @param others 自分の次の手番から順に並んだID（othersInTurnOrder の戻り値）
 *
 * 返す配列は**そのままDOMに並べる順**（上から下）。
 * 左列は「次の手番の人が最下段」に来るよう反転させてあるので、
 * CSS 側で column-reverse のような小細工をしなくてよい。
 */
export function splitMobileSeats(others: string[]): MobileSeatColumns {
  // 奇数なら左を1人多くする（自分に近い側＝手番が早い側を厚くする）
  const leftCount = Math.ceil(others.length / 2);
  return {
    left: others.slice(0, leftCount).reverse(),
    right: others.slice(leftCount),
  };
}
